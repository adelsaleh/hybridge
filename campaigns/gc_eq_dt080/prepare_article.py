def saved_torsion_curves(source, count=12):
    """Read representative construction trajectories; never recompute the flow."""
    branch = article / source['case'] / 'branch'
    run_path = branch / 'run.json'
    run = json.loads(run_path.read_text())
    metadata = json.loads((article / source['torsion_center_metadata']).read_text())
    if run['config_hash'] != metadata['config_hash']:
        raise ValueError(f'Atlas does not describe selected checkpoint: {branch}')
    number = run['config']['number_of_rays']
    # Global IDs follow equally spaced boundary-arclength seeds. Take a sparse,
    # deterministic subset across all MPI partitions, not rays from one rank.
    chosen = set(((np.arange(min(count, number)) + .5) * number
                  / min(count, number)).astype(int).tolist())
    curves = {}
    provenance = []
    for path in sorted(branch.glob('atlas_rank*.npz')):
        with np.load(path, allow_pickle=False) as data:
            ids = data['global_ray_ids']
            local = [(i, int(ray)) for i, ray in enumerate(ids) if int(ray) in chosen]
            if not local:
                continue
            if not np.allclose(data['x_T'], source['torsion_center'], rtol=0, atol=1e-10):
                raise ValueError(f'Atlas and checkpoint centers differ: {path}')
            segments, offsets = data['segments'], data['offsets']
            for index, ray in local:
                if ray in curves:
                    raise ValueError(f'Duplicate saved ray {ray}: {path}')
                start, stop = offsets[index:index + 2]
                pieces = segments[start:stop]
                points = np.concatenate((pieces[:, 0], pieces[-1:, 1]))
                if not np.isfinite(points).all():
                    raise ValueError(f'Nonfinite saved ray {ray}: {path}')
                curves[ray] = points
        provenance.append({'path': str(path.relative_to(article)),
                           'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                           'global_ray_ids': [ray for _, ray in local]})
    if set(curves) != chosen:
        raise ValueError(f'Missing saved trajectories: {chosen - set(curves)}')
    source['torsion_curves'] = {
        'selection': 'Equally spaced global boundary-arclength seed indices',
        'global_ray_ids': sorted(chosen),
        'atlas_run': str(run_path.relative_to(article)),
        'atlas_run_sha256': hashlib.sha256(run_path.read_bytes()).hexdigest(),
        'atlas_signature': run['atlas_signature'],
        'files': provenance,
        'line_style': 'dotted',
        'arrow_direction': 'center to wall (increasing normalized arclength)',
        'arrow_arclength_fractions': [.95, 1.00],
    }
    return [curves[ray] for ray in sorted(curves)]

