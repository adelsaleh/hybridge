    data = plot_data(article / source['checkpoint'])
    assert len(data[0].triangles) == source['triangles']
    artist = panel(ax, data, 'density', title)
    curves = saved_torsion_curves(source)
    ax.add_collection(LineCollection(curves, colors='white', linestyles='dotted',
                                     linewidths=.7, alpha=.8, capstyle='round', zorder=3))
    for points in curves:
        # Place one arrow by physical arclength, independent of the stored
        # trajectory's nonuniform sampling. Saved curves run center to wall.
        arclength = np.r_[0., np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))]
        positions = arclength[-1] * np.array(source['torsion_curves']['arrow_arclength_fractions'])
        tail, tip = np.column_stack([np.interp(positions, arclength, points[:, axis])
                                     for axis in range(2)])
        ax.annotate('', xy=tip, xytext=tail,
                    arrowprops={'arrowstyle': '-|>', 'color': 'white',
                                'linewidth': .6, 'mutation_scale': 8,
                                'shrinkA': 0, 'shrinkB': 0, 'alpha': .9}, zorder=4)
    ax.set_anchor('N')
    ax.set_title(title, fontsize=11, pad=5)
    ax.tick_params(labelsize=9, pad=2)
