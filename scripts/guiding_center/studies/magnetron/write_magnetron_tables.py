"""LaTeX tables of the D7 magnetron study from ``magnetron_order_efficiency`` JSON files; no time integration.

Inputs are the ``<stem>.json`` files written by ``magnetron_order_efficiency``:

* ``--ladder``: the p-ladder against the fine reference (several runs per p, one time step);
* ``--dt``: the time-step ladder on one mesh, against its finest time step as the reference;
* ``--validation NAME=JSON`` (repeatable): a run compared with its own base run (same p, same mesh,
  one setting changed); the table lists the change against the base run's error in ``--ladder``;
* ``--step-times JSON``: exclusive step timings keyed ``p<order>_K<triangles>`` (``step_wall`` in
  seconds, e.g. from a retiming alone on the GPU) that replace the campaign's shared-GPU step times
  in the main and ladder tables; runs without an entry show "--";
* ``--balance RUN.jsonl``: one run's record, whose per-step emission (source and reaction production)
  and wall fluxes are summed over each emission phase (pulse on or off, from the case's pulse train);
  ``--discharge-report PATH --hall H`` also writes that run's physics measurements (density bounds,
  anode-current peak times, periods and widths, drift angular velocity and collisional speed).

Outputs (``--main``, ``--ladder-table``, ``--dt-table``, ``--validation-table``; each optional):

* main-text table: one row per p at one ladder level (``--main-level``, index by growing unknowns),
  with the exact system sizes (HDG trace against DG element unknowns and nonzeros), the density error
  at two times, the anode-current and charge errors and the median step time;
* supplement ladder table: every ladder run, the density error at all snapshot times, the largest
  cell Courant number and the explicit-DG step ratios;
* supplement time-step table: error against the finest step and the observed order between
  consecutive steps;
* supplement validation table: the difference each check makes, next to the base run's error;
* supplement charge-balance table (``--balance-table``): per emission phase, the charge emitted, the
  charge leaving through the cathode and through the anode, and the change of the total charge.

    python -m scripts.guiding_center.studies.magnetron.write_magnetron_tables --ladder analysis/ladder.json \\
        --dt analysis/dt.json --validation "6000 curvature points=analysis/v_curv.json" \\
        --main tables/showcase.tex --ladder-table tables/magnetron_ladder.tex ...
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

HEADER = "% Generated by scripts/guiding_center/studies/magnetron/write_magnetron_tables.py\n"


def _sci(value: float, digits: int = 1) -> str:
    """LaTeX a x 10^b with ``digits`` significant digits ("--" for missing values)."""
    if value is None or not math.isfinite(value):
        return "--"
    mantissa, exponent = f"{value:.{digits - 1}e}".split("e")
    return f"${mantissa}\\times10^{{{int(exponent)}}}$"


def _count(value: float) -> str:
    """Integer with thousands separators (triangle counts)."""
    return f"{int(value):,}".replace(",", "{,}")


def _millions(value: float) -> str:
    if value >= 1e9:
        return f"{value / 1e9:.2f}G"
    return f"{value / 1e6:.2f}M" if value >= 1e5 else _count(value)


def _ms(row: dict, step_times: dict | None = None) -> str:
    """Median step time in ms; with ``step_times`` the exclusive timing of this run's (p, triangles), else "--"."""
    if step_times is not None:
        entry = step_times.get(f"p{int(row['order'])}_K{int(row['triangles'])}")
        return "--" if entry is None else f"{1e3 * float(entry['step_wall']):.0f}"
    step = row.get("step_wall")
    return "--" if step is None else f"{1e3 * step:.0f}"


def _density(row: dict, time: float) -> float | None:
    errors = row.get("density_l2") or {}
    for key, value in errors.items():
        if abs(float(key) - time) < 1e-9:
            return value
    return None


def _by_order(rows: list[dict]) -> dict[int, list[dict]]:
    groups: dict[int, list[dict]] = {}
    for row in rows:
        groups.setdefault(int(row["order"]), []).append(row)
    return {order: sorted(members, key=lambda r: r["density_unknowns"]) for order, members in sorted(groups.items())}


def main_table(ladder: dict, level: int, times: tuple[float, float], step_times: dict | None = None) -> str:
    """One row per p at one ladder level: sizes, errors against the reference, step time."""
    reference = ladder["reference"]
    lines = [r"\setlength{\tabcolsep}{4pt}\begin{tabular}{rrrrrrrrrr}\toprule",
             r"$p$ & triangles & density & trace / DG & trace / DG & "
             rf"$\rho$ error, $t={times[0]:g}$ & $\rho$ error, $t={times[1]:g}$ & current & charge & ms/step\\",
             r" &  & unknowns & unknowns & nonzeros & (rel. $L^2$) & (rel. $L^2$) & (rel. $L^2$ in $t$) & (max, rel.) & \\\midrule"]
    for order, members in _by_order(ladder["runs"]).items():
        row = members[min(level, len(members) - 1)]
        lines.append(
            f"{order} & {_count(row['triangles'])} & {_millions(row['density_unknowns'])} & "
            f"{_millions(row['trace_unknowns'])} / {_millions(row['dg_element_unknowns'])} & "
            f"{_millions(row['trace_nonzeros'])} / {_millions(row['dg_element_nonzeros'])} & "
            f"{_sci(_density(row, times[0]), 2)} & {_sci(_density(row, times[1]), 2)} & "
            f"{_sci(row['current_l2'], 2)} & {_sci(row['charge_max'], 2)} & {_ms(row, step_times)}\\\\")
    lines.append(r"\midrule")
    lines.append(f"ref.\\ {reference['order']} & {_count(reference['triangles'])} & "
                 f"{_millions(reference['density_unknowns'])} & "
                 f"{_millions(reference['trace_unknowns'])} / {_millions(reference['dg_element_unknowns'])} & "
                 f"{_millions(reference['trace_nonzeros'])} / {_millions(reference['dg_element_nonzeros'])} & "
                 f"-- & -- & -- & -- & {_ms(reference, step_times)}\\\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def ladder_table(ladder: dict, step_times: dict | None = None) -> str:
    """Every ladder run: errors at all snapshot times, Courant number, explicit step ratios, step time."""
    times = [float(t) for t in ladder["times"]]
    heads = " & ".join(rf"$t={t:g}$" for t in times)
    lines = [r"\setlength{\tabcolsep}{3.5pt}\begin{tabular}{rrr" + "r" * len(times) + r"rrrrrrr}\toprule",
             rf"$p$ & triangles & unknowns & {heads} & current & charge & $\min\rho_h$ & $C_{{\max}}$ & "
             r"expl.\ adv.\ & expl.\ diff.\ & ms/step\\\midrule"]
    for order, members in _by_order(ladder["runs"]).items():
        for row in members:
            errors = " & ".join(_sci(_density(row, t)) for t in times)
            lines.append(
                f"{order} & {_count(row['triangles'])} & {_millions(row['density_unknowns'])} & {errors} & "
                f"{_sci(row['current_l2'])} & {_sci(row['charge_max'])} & {_sci(row['rho_min'], 2)} & "
                f"{row['courant_max']:.0f} & {row['explicit_advective_step_ratio']:.0f} & "
                f"{row['explicit_diffusive_step_ratio_estimate']:.0f} & {_ms(row, step_times)}\\\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def dt_table(ladder: dict, time: float) -> str:
    """Time-step ladder against the finest step on the same mesh, with observed orders."""
    rows = sorted(ladder["runs"], key=lambda r: -r["dt"])
    lines = [r"\setlength{\tabcolsep}{4.5pt}\begin{tabular}{rrrrrrr}\toprule",
             rf"$\Delta t$ & $\rho$ error, $t={time:g}$ & order & current & order & charge & order\\\midrule"]
    previous = None
    for row in rows:
        values = (_density(row, time), row["current_l2"], row["charge_max"])
        cells = []
        for value, before in zip(values, previous or (None, None, None)):
            order = ("--" if before is None or not value or not before
                     else f"{math.log(before / value) / math.log(2):.2f}")
            cells.append(f"{_sci(value, 2)} & {order}")
        lines.append(f"{row['dt']:g} & " + " & ".join(cells) + r"\\")
        previous = values
    lines.append(rf"{ladder['reference']['dt']:g} & \multicolumn{{6}}{{l}}{{reference}}\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def validation_table(checks: list[tuple[str, dict]], ladder: dict, time: float) -> str:
    """Difference each check makes (run against its base run) next to the base run's error in the ladder.

    Each check is read at the latest snapshot time it holds up to ``time`` (a short check stops earlier),
    and the base run's error is taken at that same time.
    """
    lines = [r"\setlength{\tabcolsep}{4.5pt}\begin{tabular}{lrrrrrr}\toprule",
             r"check & unknowns & $t$ & $\rho$ difference & current & charge & base run's $\rho$ error\\\midrule"]
    base_rows = {(int(r["order"]), int(r["triangles"])): r for r in ladder["runs"]}
    for name, result in checks:
        base = base_rows.get((int(result["reference"]["order"]), int(result["reference"]["triangles"])))
        for row in result["runs"]:
            held = [float(k) for k in (row.get("density_l2") or {}) if float(k) <= time + 1e-9]
            at = max(held) if held else time
            error = None if base is None else _density(base, at)
            lines.append(f"{name} & {_millions(row['density_unknowns'])} & {at:g} & {_sci(_density(row, at))} & "
                         f"{_sci(row['current_l2'])} & {_sci(row['charge_max'])} & {_sci(error)}\\\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def _phases(pulse, times: list[float]) -> list[tuple[str, float, float]]:
    """Intervals of ``[0, T]`` on which the pulse is on (rate > 1/2) or off, from a fine sampling."""
    end = times[-1]
    grid = [end * k / 20000 for k in range(20001)]
    on = [pulse(t) > 0.5 for t in grid]
    phases, start = [], 0.0
    for k in range(1, len(grid)):
        if on[k] != on[k - 1]:
            phases.append(("on" if on[k - 1] else "off", start, grid[k]))
            start = grid[k]
    phases.append(("on" if on[-1] else "off", start, end))
    return phases


def balance_table(jsonl: Path) -> str:
    """Charge balance of one run summed over the emission phases (rectangle rule over the steps).

    In each phase, ``emission`` is the integral of the source and reaction production, ``cathode``
    and ``anode`` the charge leaving through those walls (negative when the wall data feed the
    domain), and the last column the change of the total charge, which the three reproduce up to the
    time quadrature.
    """
    from scripts.guiding_center.cases.guiding_center_cases import pulse_train

    records = [json.loads(line) for line in Path(jsonl).read_text().splitlines() if line.strip()]
    parameters = next(r["run_configuration"]["case_parameters"] for r in records if r.get("run_configuration"))
    rows = [r for r in records if r.get("step", 0) > 0 and "mass" in r]
    train = pulse_train(parameters["emission_period"], parameters.get("emission_duty", 0.5), parameters.get("emission_ramp"))
    phase = float(parameters.get("emission_phase", 0.0))
    times = [float(r["time"]) for r in rows]
    mass = [float(r["mass"]) for r in rows]
    steps = [times[0]] + [b - a for a, b in zip(times, times[1:])]
    initial = next((float(r["mass"]) for r in records if r.get("step") == 0 and "mass" in r), mass[0])

    def total(key, select) -> float:
        return sum(float(rows[k].get(key) or 0.0) * steps[k] for k in select)

    lines = [r"\setlength{\tabcolsep}{5pt}\begin{tabular}{llrrrr}\toprule",
             r"emission & $t$ & emitted & through cathode & through anode & charge change\\\midrule"]
    for kind, start, stop in _phases(lambda t: train(t + phase), times):
        select = [k for k, t in enumerate(times) if start < t <= stop + 1e-12]
        if not select:
            continue
        emitted = total("source_production", select) + total("reaction_production", select)
        cathode, anode = total("wall_outflux_inner", select), total("wall_outflux_outer", select)
        before = mass[select[0] - 1] if select[0] > 0 else initial
        change = mass[select[-1]] - before
        lines.append(f"{kind} & ${start:g}$--${stop:g}$ & ${emitted:.3f}$ & ${cathode:.3f}$ & ${anode:.3f}$ & "
                     f"${change:+.3f}$\\\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def discharge_report(jsonl: Path, hall: float, pixels: int = 1400) -> str:
    """Physics measurements of one run: density bounds, anode-current peaks, drift angular velocity.

    The current peaks are found on the second half of the run (prominence a tenth of the largest
    current) and compared with one vane pitch at the wave's angular velocity, pi / (N W). The
    angle-averaged radial field of each snapshot from t = 10 on gives the angular velocity E_r / r
    of the drift inside the hub (0.52 <= r <= 0.67), the radius where it equals W, and the
    collisional outward speed E_r / h across the gap.
    """
    import numpy as np
    from scipy.signal import find_peaks, peak_widths

    from scripts.guiding_center.studies.magnetron.plot_discharge import _Snapshots

    records = [json.loads(line) for line in Path(jsonl).read_text().splitlines() if line.strip()]
    parameters = next(r["run_configuration"]["case_parameters"] for r in records if r.get("run_configuration"))
    rows = [r for r in records if r.get("step", 0) > 0 and "mass" in r]
    mode, speed = int(parameters["wave_mode"]), float(parameters["wave_speed"])
    t = np.array([float(r["time"]) for r in rows])
    current = np.array([float(r["wall_outflux_outer"]) for r in rows])
    out = [f"run: {Path(jsonl).name}", f"steps: {len(rows)}, T = {t[-1]:g}, wave mode N = {mode}, speed W = {speed:g}",
           f"density maximum over the run: {max(float(r['rho_max']) for r in rows):.6f}",
           f"sampled density minimum over the run: {min(float(r['rho_min']) for r in rows):.3e}"]
    speeds = [float(r["velocity_max_speed"]) for r in rows if r.get("velocity_max_speed") is not None]
    if speeds:
        out.append(f"largest logged drift speed: {max(speeds):.3f}")
    peak = float(current.max())
    for fraction in (1e-4, 1e-2):
        out.append(f"anode current first exceeds {fraction:g} of its maximum at t = {t[current > fraction * peak][0]:.2f}")
    late = t > 0.5 * t[-1]
    peaks, _ = find_peaks(current[late], prominence=0.1 * peak)
    widths = peak_widths(current[late], peaks, rel_height=0.5)[0] * float(np.median(np.diff(t)))
    troughs, _ = find_peaks(-current[late], prominence=0.1 * peak)
    times = t[late][peaks]
    out += [f"anode-current peaks (t > {0.5 * t[-1]:g}): " + ", ".join(f"{v:.2f}" for v in times),
            f"peak intervals: {np.diff(times).min():.3f}-{np.diff(times).max():.3f}, mean {np.diff(times).mean():.3f}; "
            f"pi / (N W) = {math.pi / (mode * speed):.3f}",
            f"peak widths at half height: {widths.min():.2f}-{widths.max():.2f}",
            f"peak currents {current[late][peaks].min():.4f}-{current[late][peaks].max():.4f}, "
            f"trough currents {current[late][troughs].min():.4f}-{current[late][troughs].max():.4f}"]
    snapshots = _Snapshots(Path(jsonl))
    half = float(np.max(np.abs(snapshots.npz["node_coords"]))) * 1.001
    geometry = snapshots.grid(pixels, (-half, half, -half, half))
    step = 2 * half / pixels
    x = -half + (np.arange(pixels) + 0.5) * step
    xx, yy = np.meshgrid(x, x[::-1])
    r = np.hypot(xx, yy)
    for time in [float(v) for v in snapshots.npz["times"] if v >= 10.0 - 1e-9]:
        phi = np.asarray(snapshots.potential(geometry, time), dtype=float).reshape(pixels, pixels)
        gy, gx = np.gradient(phi, -step, step)
        radial = -(gx * xx + gy * yy) / np.maximum(r, 1e-12)
        valid = np.isfinite(radial)
        bins = np.arange(0.52, 1.0, 0.02)
        omega, collisional = [], []
        for a in bins:
            ring = valid & (r >= a) & (r < a + 0.02)
            field = float(np.mean(radial[ring])) if ring.sum() >= 50 else math.nan
            omega.append(field / (a + 0.01)), collisional.append(field / hall)
        omega, collisional = np.array(omega), np.array(collisional)
        hub = np.nanmean(omega[bins + 0.01 <= 0.67])
        below = np.flatnonzero(np.nan_to_num(omega, nan=math.inf) <= speed)
        synchronous = f"{bins[below[0]] + 0.01:.2f}" if below.size else "none"
        out.append(f"t = {time:g}: drift angular velocity E_r/r = {hub:.3f} in the hub (r <= 0.67), equal to W at r = {synchronous}; "
                   f"collisional speed E_r/h = {np.nanmin(collisional):.4f}-{np.nanmax(collisional):.4f} for 0.52 <= r < 1")
    return "\n".join(out) + "\n"


def _load(path: Path) -> dict:
    return json.loads(Path(path).read_text())


def _check(text: str) -> tuple[str, Path]:
    name, _, path = text.rpartition("=")  # the name may hold LaTeX with "=", the path may not
    if not name or not path:
        raise argparse.ArgumentTypeError("expected NAME=JSON")
    return name, Path(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ladder", type=Path, required=True, help="magnetron_order_efficiency JSON of the p-ladder")
    parser.add_argument("--dt", type=Path, help="magnetron_order_efficiency JSON of the time-step ladder")
    parser.add_argument("--validation", type=_check, action="append", default=[], metavar="NAME=JSON")
    parser.add_argument("--main", type=Path, help="main-text table (one level per p)")
    parser.add_argument("--main-level", type=int, default=1, help="ladder level per p by growing unknowns (default 1)")
    parser.add_argument("--main-times", type=lambda s: tuple(float(v) for v in s.split(",")), default=(20., 40.))
    parser.add_argument("--ladder-table", type=Path)
    parser.add_argument("--dt-table", type=Path)
    parser.add_argument("--validation-table", type=Path)
    parser.add_argument("--time", type=float, default=40., help="snapshot time of the dt and validation tables")
    parser.add_argument("--step-times", type=Path, help="exclusive step timings JSON keyed p<order>_K<triangles>")
    parser.add_argument("--balance", type=Path, help="run record JSONL for the charge-balance table")
    parser.add_argument("--balance-table", type=Path)
    parser.add_argument("--discharge-report", type=Path, help="text report of the --balance run's physics measurements")
    parser.add_argument("--hall", type=float, help="Hall parameter h of the run (collisional speed E_r / h in the report)")
    args = parser.parse_args()
    ladder = _load(args.ladder)
    step_times = _load(args.step_times) if args.step_times else None
    if args.main:
        args.main.write_text(HEADER + main_table(ladder, args.main_level, args.main_times, step_times))
        print(args.main)
    if args.ladder_table:
        args.ladder_table.write_text(HEADER + ladder_table(ladder, step_times))
        print(args.ladder_table)
    if args.dt_table:
        if args.dt is None:
            parser.error("--dt-table needs --dt")
        args.dt_table.write_text(HEADER + dt_table(_load(args.dt), args.time))
        print(args.dt_table)
    if args.validation_table:
        checks = [(name, _load(path)) for name, path in args.validation]
        args.validation_table.write_text(HEADER + validation_table(checks, ladder, args.time))
        print(args.validation_table)
    if args.balance_table:
        if args.balance is None:
            parser.error("--balance-table needs --balance")
        args.balance_table.write_text(HEADER + balance_table(args.balance))
        print(args.balance_table)
    if args.discharge_report:
        if args.balance is None or args.hall is None:
            parser.error("--discharge-report needs --balance and --hall")
        args.discharge_report.write_text(discharge_report(args.balance, args.hall))
        print(args.discharge_report)


if __name__ == "__main__":
    main()
